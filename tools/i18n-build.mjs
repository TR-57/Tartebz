#!/usr/bin/env node
/*
 | Builds the translation catalogue.
 |   node tools/i18n-build.mjs           – write files and print the summary
 |   node tools/i18n-build.mjs --strict  – also fail (exit 1) when a key has no Arabic (use before release)
 |
 | Sources
 |   assets/js/data.js       storefront keyed texts (TZ.i18n.en / TZ.i18n.ar)
 |   i18n/site-phrases.json  storefront phrases {English: Arabic} (optional)
 |   admin/i18n/ar.json      admin phrases {phrases: {English: Arabic}, patterns: [[regex, replacement]]}
 | Outputs (kept in version control)
 |   i18n/catalog.json       { site: { keys: {key: {en, ar, where}}, phrases: {en: {ar, where}} }, admin: { phrases: {en: ar} } }
 |   admin/js/i18n-dict.js   window.ADMIN_I18N = { phrases, patterns }
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.relative(root, p).split(path.sep).join('/');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const strict = process.argv.includes('--strict');

// ---- storefront keys ----
const sandbox = { window: {} };
sandbox.TZ = sandbox.window.TZ = {};
vm.runInNewContext(read('assets/js/data.js'), sandbox);
const dict = sandbox.window.TZ.i18n || {};
const en = dict.en || {};
const ar = dict.ar || {};

// Where each key is used: data-i18n* attributes in pages, TZ.t('key') / t("key", …) calls in scripts.
const where = {};
const files = [];
for (const f of fs.readdirSync(root)) if (f.endsWith('.html')) files.push(path.join(root, f));
for (const f of fs.readdirSync(path.join(root, 'assets/js'))) if (f.endsWith('.js')) files.push(path.join(root, 'assets/js', f));
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const re = /data-i18n(?:-html|-ph|-aria)?="([\w.-]+)"|\bt\(\s*['"]([\w.-]+)['"]/g;
  let m;
  while ((m = re.exec(src))) {
    const k = m[1] || m[2];
    (where[k] ||= new Set()).add(rel(f));
  }
}

const keys = {};
let noArabic = [];
const flat = (prefix, v, out) => {
  if (Array.isArray(v)) v.forEach((x, i) => flat(`${prefix}.${i}`, x, out));
  else out[prefix] = String(v);
};
const enFlat = {}, arFlat = {};
for (const [k, v] of Object.entries(en)) flat(k, v, enFlat);
for (const [k, v] of Object.entries(ar)) flat(k, v, arFlat);
for (const k of Object.keys(enFlat).sort()) {
  const base = k.split('.')[0];
  keys[k] = { en: enFlat[k], ar: arFlat[k] || '', where: [...(where[base] || [])].join(', ') };
  if (!arFlat[k] || !arFlat[k].trim()) noArabic.push(k);
}
// Keys used in pages but missing from the dictionary.
const unknown = Object.keys(where).filter((k) => !(k in en) && !/[_.]$/.test(k)); // 'sour_' + level etc. are built at run time

// ---- storefront phrases ----
let sitePhrases = {};
if (fs.existsSync(path.join(root, 'i18n/site-phrases.json'))) {
  const sp = JSON.parse(read('i18n/site-phrases.json'));
  for (const [e, a] of Object.entries(sp)) sitePhrases[e] = { ar: a, where: '' };
}

// ---- admin phrases ----
const adminSrc = JSON.parse(read('admin/i18n/ar.json'));
const adminPhrases = adminSrc.phrases || {};
const patterns = adminSrc.patterns || [];
for (const [, , ] of patterns) { /* validated below */ }
patterns.forEach(([re]) => { new RegExp(re); });

// ---- write ----
fs.mkdirSync(path.join(root, 'i18n'), { recursive: true });
const catalog = { site: { keys, phrases: sitePhrases }, admin: { phrases: adminPhrases } };
fs.writeFileSync(path.join(root, 'i18n/catalog.json'), JSON.stringify(catalog, null, 1) + '\n');
fs.writeFileSync(path.join(root, 'admin/js/i18n-dict.js'),
  '/* Generated by tools/i18n-build.mjs from admin/i18n/ar.json – do not edit by hand. */\n' +
  'window.ADMIN_I18N=' + JSON.stringify({ phrases: adminPhrases, patterns }) + ';\n');

console.log(`keys ${Object.keys(keys).length} (no Arabic: ${noArabic.length}) | site phrases ${Object.keys(sitePhrases).length} | admin phrases ${Object.keys(adminPhrases).length} | admin patterns ${patterns.length}`);
if (noArabic.length) console.log('Keys without Arabic: ' + noArabic.join(', '));
if (unknown.length) console.log('Keys used in pages but not in the dictionary: ' + unknown.join(', '));
if (strict && (noArabic.length || unknown.length)) process.exit(1);
